"""
Полноценный многошаговый AI-движок генерации опросов и викторин для StomChat.

Архитектура пайплайна:
  - Шаг 1: Контекстный триаж темы (Topic & Context Triage)
    Анализ сообщений чата за последние 24ч (или переданного контекста).
    Если шло бурное клиническое обсуждение — опрос строится на его основе.
    Если затишье — выбор темы из недельного клинического рубрикатора:
      Пн: Эндодонтия
      Вт: Ортопедия
      Ср: Хирургия/Имплантология
      Чт: Терапия/Адгезия
      Пт: Батл материалов (Speedex vs А-силикон и др.)
      Сб: Лайфстайл/Разгрузка
      Вс: Клинический консилиум и разбор сложных случаев
  - Шаг 2: Триаж формата и типа (Format & Mode Triage)
    'quiz' — клиническая задача с 1 правильным ответом, объяснением в лампочке (💡).
    'regular' — опрос мнений / батл материалов (без правильного ответа, с процентами).
    'lifestyle' — разгрузка/юмор на выходные.
    Определение необходимости отдельного вводного поста (case_intro).
  - Шаг 3: Генератор контента (Content Generation)
    Генерация строгого JSON с полями:
    case_intro, question, options, correct_option_id, explanation_brief, explanation_deep.
  - Шаг 4: Санитизация и валидация (Sanitization & Guardrails)
    Проверка лимитов Telegram:
      len(question) <= 300
      2 <= len(options) <= 10
      len(opt) <= 100 для каждого варианта
      len(explanation_brief) <= 200
    Аккуратный срез по границе слов без поломки HTML-тегов.
  - Шаг 5: Надежные фолбэки (POLL_FALLBACK_PRESETS)
    Готовый пул клинических задач при недоступности LLM (503, исчерпание ключей).
  - Telethon MTProto Builder:
    build_poll_media(...) с поддержкой InputMediaPoll, HTML-парсинга,
    public_voters и валидацией close_period (5..600 сек).
"""

