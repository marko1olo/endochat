def truncate_html_aware(text: str, max_len: int, ellipsis: str = "...") -> str:
    """
    Обрезает текст до max_len символов по границе слов без нарушения HTML-разметки.
    Автоматически закрывает открытые HTML-теги в корректном порядке.
    Гарантирует, что telethon.extensions.html.parse(result)[0] <= max_len.
    """
    if not text:
        return ""

    text = text.strip()
    try:
        plain_len = len(html.parse(text)[0])
    except Exception:
        plain_len = len(text)

    if plain_len <= max_len:
        return text

    target_plain_len = max_len - len(ellipsis) if max_len > len(ellipsis) else max_len
    if target_plain_len <= 0:
        return text[:max_len]

    token_pattern = re.compile(r"(<[^>]+>|[^<]+)")
    tokens = token_pattern.findall(text)

    open_tags: List[str] = []
    res_tokens: List[str] = []
    current_plain_len = 0

    for token in tokens:
        if token.startswith("<") and token.endswith(">"):
            tag_content = token[1:-1].strip()
            if tag_content.startswith("/"):
                # Закрывающий тег
                tag_name = tag_content[1:].split()[0].lower()
                if open_tags and open_tags[-1] == tag_name:
                    open_tags.pop()
                res_tokens.append(token)
            elif not tag_content.endswith("/"):
                # Открывающий тег
                tag_name = tag_content.split()[0].lower()
                open_tags.append(tag_name)
                res_tokens.append(token)
            else:
                # Одиночный тег (например <br/>)
                res_tokens.append(token)
        else:
            # Текстовый токен
            if current_plain_len + len(token) <= target_plain_len:
                res_tokens.append(token)
                current_plain_len += len(token)
            else:
                available = target_plain_len - current_plain_len
                sub = token[:available]
                last_space = max(sub.rfind(" "), sub.rfind("\n"), sub.rfind("\t"))
                if last_space > 0:
                    sub = sub[:last_space].rstrip(",.;:!? ")
                res_tokens.append(sub + ellipsis)
                current_plain_len += len(sub) + len(ellipsis)
                break

    # Закрываем все незакрытые теги в обратном порядке
    for tag in reversed(open_tags):
        res_tokens.append(f"</{tag}>")

    result = "".join(res_tokens).strip()

    # Финальная страховка длины через html.parse
    try:
        p_len = len(html.parse(result)[0])
        if p_len > max_len:
            plain_only = html.parse(result)[0]
            cutoff = max_len - len(ellipsis) if max_len > len(ellipsis) else max_len
            sub_cut = plain_only[:cutoff]
            last_space = sub_cut.rfind(" ")
            if last_space > 0:
                sub_cut = sub_cut[:last_space].rstrip(",.;:!? ")
            result = sub_cut + ellipsis
    except Exception:
        if len(result) > max_len:
            result = result[:max_len]

    return result


def sanitize_poll_payload(payload: Union[PollPayload, Dict[str, Any]]) -> Optional[PollPayload]:
    """
    Санитизирует и валидирует структуру опроса/викторины под строгие лимиты Telegram:
      - question: <= 300 символов (срез по границе слов без поломки тегов)
      - options: от 2 до 10 вариантов, каждый <= 100 символов
      - explanation_brief: <= 200 символов
      - correct_option_id: валидируется для quiz, сбрасывается в None для regular/lifestyle
    Возвращает PollPayload или None, если опрос невозможно санитизировать (менее 2 опций или пустой вопрос).
    """
    if isinstance(payload, PollPayload):
        q = payload.question
        opts = list(payload.options)
        p_type = payload.poll_type
        c_id = payload.correct_option_id
        exp_b = payload.explanation_brief
        exp_d = payload.explanation_deep
        c_intro = payload.case_intro
        topic = payload.topic
        source = payload.source
        cat = payload.category
        seed_q = payload.discussion_seed_question
    elif isinstance(payload, dict):
        q = str(payload.get("question", "")).strip()
        opts = [str(o).strip() for o in payload.get("options", []) if str(o).strip()]
        raw_val = payload.get("poll_type", PollType.QUIZ)
        if isinstance(raw_val, PollType):
            p_type = raw_val
        else:
            raw_type = str(raw_val).lower()
            if raw_type in ("regular", "poll", "polltype.regular"):
                p_type = PollType.REGULAR
            elif raw_type in ("lifestyle", "humor", "offtopic", "polltype.lifestyle"):
                p_type = PollType.LIFESTYLE
            else:
                p_type = PollType.QUIZ
        c_id = payload.get("correct_option_id")
        if c_id is not None:
            try:
                c_id = int(c_id)
            except (ValueError, TypeError):
                c_id = None
        exp_b = str(payload.get("explanation_brief", "")).strip()
        exp_d = str(payload.get("explanation_deep", "")).strip()
        c_intro = payload.get("case_intro")
        if c_intro is not None:
            c_intro = str(c_intro).strip()
            if not c_intro:
                c_intro = None
        topic = str(payload.get("topic", "")).strip()
        source = str(payload.get("source", "llm"))
        cat = str(payload.get("category", "")).strip()
        seed_q = payload.get("discussion_seed_question")
    else:
        return None

    # Санитизация вопроса
    clean_question = truncate_html_aware(q, MAX_QUESTION_LEN)
    if not clean_question:
        return None

    # Сохраняем исходный текст правильного ответа для защиты от сдвига индекса
    orig_correct_text = None
    if c_id is not None and 0 <= c_id < len(opts):
        orig_correct_text = str(opts[c_id]).strip()

    # Санитизация вариантов ответа
    sanitized_opts: List[str] = []
    seen = set()
    for opt in opts[:MAX_OPTIONS_COUNT]:
        opt_clean = truncate_html_aware(opt, MAX_OPTION_LEN)
        if opt_clean and opt_clean.lower() not in seen:
            sanitized_opts.append(opt_clean)
            seen.add(opt_clean.lower())

    if len(sanitized_opts) < MIN_OPTIONS_COUNT:
        return None

    # Санитизация типа и правильного ответа (с восстановлением индекса при дедупликации)
    if p_type == PollType.QUIZ:
        relocated_cid = None
        if orig_correct_text:
            clean_orig = truncate_html_aware(orig_correct_text, MAX_OPTION_LEN).lower()
            for idx, s_opt in enumerate(sanitized_opts):
                if s_opt.lower() == clean_orig:
                    relocated_cid = idx
                    break
        if relocated_cid is not None:
            c_id = relocated_cid
        elif c_id is None or not (0 <= c_id < len(sanitized_opts)):
            c_id = 0
    else:
        c_id = None

    # Санитизация краткого объяснения для лампочки
    clean_exp_b = truncate_html_aware(exp_b, MAX_EXPLANATION_LEN) if exp_b else ""
    if p_type == PollType.QUIZ and not clean_exp_b:
        clean_exp_b = "Правильный клинический ответ!"

    # Санитизация введения и глубокого разбора под лимит сообщения Telegram (4096 символов)
    clean_c_intro = truncate_html_aware(c_intro, MAX_CASE_INTRO_LEN) if c_intro else None
    clean_exp_d = truncate_html_aware(exp_d, MAX_DEEP_EXPLANATION_LEN) if exp_d else ""
    clean_seed_q = truncate_html_aware(str(seed_q).strip(), 350) if seed_q else None

    return PollPayload(
        question=clean_question,
        options=sanitized_opts,
        poll_type=p_type,
        correct_option_id=c_id,
        explanation_brief=clean_exp_b,
        explanation_deep=clean_exp_d,
        case_intro=clean_c_intro,
        topic=topic,
        category=cat,
        source=source,
        discussion_seed_question=clean_seed_q
    )


def generate_evening_poll_debrief(
    payload: Optional[PollPayload] = None,
    vote_stats: Optional[Dict[str, Any]] = None,
    *,
    explanation_deep: Optional[str] = None,
    discussion_seed_question: Optional[str] = None,
) -> str:
    """
    Формирует живой текст вечернего разбора опроса с клиническим обоснованием
    и открытым вопросом-катализатором для практикующих врачей чата.
    Поддерживает как передачу PollPayload, так и прямые аргументы (explanation_deep, discussion_seed_question).
    """
    deep_exp = (explanation_deep or (payload.explanation_deep if payload else "") or "").strip()
    seed_q = (discussion_seed_question or (payload.discussion_seed_question if payload else "") or "").strip()
    brief_exp = (payload.explanation_brief if payload else "") or ""

    parts = ["🏁 <b>Клинический разбор кейса:</b>\n"]

    if vote_stats and vote_stats.get("total_votes", 0) > 0:
        total = vote_stats["total_votes"]
        poll_type = vote_stats.get("poll_type") or (payload.poll_type.value if payload else "quiz")
        if str(poll_type).lower() == "quiz":
            acc = vote_stats.get("accuracy_percent", 0.0)
            parts.append(f"📊 <i>Итоги викторины: проголосовало {total} коллег, верный ответ выбрали {acc}%.</i>\n")
        else:
            parts.append(f"📊 <i>Итоги опроса: мнением поделились {total} коллег.</i>\n")

    if deep_exp:
        parts.append(deep_exp)
    elif brief_exp:
        parts.append(brief_exp)
    else:
        parts.append("Выбранная тактика обеспечивает надежный биомеханический прогноз и сохраняет зуб.")

    if seed_q:
        parts.append(f"\n\n💬 <b>Вопрос к коллегам:</b>\n{seed_q}")
    else:
        parts.append("\n\n💬 <b>Вопрос к коллегам:</b>\nКоллеги, кто сталкивался с подобной клинической развилкой на практике — какую тактику обычно выбираете у кресла?")

    return "\n".join(parts)


