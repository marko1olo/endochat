def build_poll_media(
    question: str,
    options: List[str],
    poll_type: str = "quiz",
    correct_idx: Optional[int] = 0,
    explanation: str = "",
    is_anonymous: bool = True,
    open_period: Optional[int] = None
) -> types.InputMediaPoll:
    """
    Собирает types.InputMediaPoll для Telethon 1.42.0.

    Параметры:
      - question: Текст вопроса (поддерживает HTML разметку, до 300 символов).
      - options: Список вариантов ответов (от 2 до 10 вариантов, каждый до 100 символов).
      - poll_type: 'quiz' или 'regular' / 'lifestyle'.
      - correct_idx: 0-based индекс правильного ответа (обязателен для quiz, игнорируется для regular).
      - explanation: Пояснение правильного ответа в лампочке (до 200 символов, поддерживает HTML).
      - is_anonymous: Анонимное голосование (public_voters = not is_anonymous).
      - open_period: Время жизни опроса в секундах (валидируется от 5 до 600 сек или None).
    """
    if not question or not str(question).strip():
        raise ValueError("Poll question cannot be empty")

    if not options or not (MIN_OPTIONS_COUNT <= len(options) <= MAX_OPTIONS_COUNT):
        raise ValueError(f"Poll options count must be between {MIN_OPTIONS_COUNT} and {MAX_OPTIONS_COUNT}, got {len(options) if options else 0}")

    # Валидация open_period (MTProto close_period)
    close_period: Optional[int] = None
    if open_period is not None:
        if not (MIN_CLOSE_PERIOD <= open_period <= MAX_CLOSE_PERIOD):
            raise ValueError(
                f"open_period (close_period) must be between {MIN_CLOSE_PERIOD} and {MAX_CLOSE_PERIOD} seconds, got {open_period}"
            )
        close_period = int(open_period)

    is_quiz = (str(poll_type).lower() == "quiz")

    # Валидация correct_idx для викторины
    if is_quiz:
        if correct_idx is None or not (0 <= correct_idx < len(options)):
            raise ValueError(f"correct_idx must be between 0 and {len(options) - 1} for quiz, got {correct_idx}")

    # Защитная санитизация длин строк по лимитам MTProto
    clean_q = truncate_html_aware(question, MAX_QUESTION_LEN)
    clean_options = [truncate_html_aware(opt, MAX_OPTION_LEN) for opt in options]

    # Обработка HTML-сущностей вопроса
    q_text, q_entities = html.parse(clean_q)
    q_twe = types.TextWithEntities(text=q_text, entities=q_entities or [])

    # Сборка ответов опроса
    poll_answers: List[types.PollAnswer] = []
    correct_answers_bytes: Optional[List[bytes]] = [] if is_quiz else None

    for i, opt in enumerate(clean_options):
        opt_text, opt_entities = html.parse(opt)
        opt_twe = types.TextWithEntities(text=opt_text, entities=opt_entities or [])
        opt_bytes = str(i).encode("utf-8")
        poll_answers.append(types.PollAnswer(text=opt_twe, option=opt_bytes))

        if is_quiz and i == correct_idx:
            correct_answers_bytes.append(opt_bytes)

    # Обработка лампочки (solution) для quiz
    sol_text: Optional[str] = None
    sol_entities: Optional[List[types.TypeMessageEntity]] = None
    if is_quiz and explanation:
        clean_exp = truncate_html_aware(explanation, MAX_EXPLANATION_LEN)
        sol_text, sol_entities = html.parse(clean_exp)

    # Генерация уникального ID опроса
    poll_id = random.randint(1, (1 << 63) - 1)

    poll = types.Poll(
        id=poll_id,
        question=q_twe,
        answers=poll_answers,
        closed=False,
        public_voters=(not is_anonymous),
        multiple_choice=False,
        quiz=is_quiz,
        close_period=close_period,
        close_date=None
    )

    media = types.InputMediaPoll(
        poll=poll,
        correct_answers=correct_answers_bytes,
        solution=sol_text,
        solution_entities=sol_entities
    )

    return media


