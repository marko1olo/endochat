def extract_chat_text(chat_context: Union[str, List[Any], None]) -> str:
    """Извлекает единый текст из переданного контекста чата."""
    if not chat_context:
        return ""
    if isinstance(chat_context, str):
        return chat_context.strip()
    if isinstance(chat_context, list):
        parts: List[str] = []
        for item in chat_context:
            if isinstance(item, str):
                parts.append(item.strip())
            elif isinstance(item, dict):
                text_val = item.get("text") or item.get("message") or ""
                if text_val:
                    parts.append(str(text_val).strip())
            elif hasattr(item, "text"):
                val = getattr(item, "text", "")
                if val:
                    parts.append(str(val).strip())
            elif hasattr(item, "message"):
                val = getattr(item, "message", "")
                if val:
                    parts.append(str(val).strip())
        return "\n".join(p for p in parts if p)
    return str(chat_context).strip()


def get_weekly_rubric(
    dt: Optional[datetime.datetime] = None,
    recent_polls: Optional[List[Dict[str, Any]]] = None
) -> Dict[str, Any]:
    """Возвращает рубрику недели для заданной даты с учетом ротации подтем по неделям месяца и исключения недавних тем."""
    now = dt or datetime.datetime.now()
    weekday = now.weekday()
    base_rubric = WEEKLY_RUBRICATOR.get(weekday, WEEKLY_RUBRICATOR[0])
    rubric = dict(base_rubric)
    subtopics = base_rubric.get("subtopics", [])
    if subtopics:
        # Ротация по номеру недели в месяце с учетом времени суток (утро < 13:00 vs день >= 13:00)
        slot_offset = 1 if now.hour >= 13 else 0
        default_idx = (((now.day - 1) // 7) + slot_offset) % len(subtopics)
        chosen_subtopic = subtopics[default_idx]

        # Если передан список недавних опросов — выбираем подтему, которой не было в недавних опросах
        if recent_polls:
            recent_texts = " ".join(str(p.get("question", "") + " " + p.get("topic", "")).lower() for p in recent_polls[:14])
            available = [st for st in subtopics if not any(kw in recent_texts for kw in st.lower().split()[:2])]
            if available:
                chosen_subtopic = available[default_idx % len(available)]

        rubric["subtopic"] = chosen_subtopic
        rubric["topic"] = f"{base_rubric['topic'].split('(')[0].strip()}: {chosen_subtopic}"
    return rubric


def detect_chat_discussion_heuristic(chat_text: str) -> Optional[Tuple[str, str, PollType]]:
    """
    Эвристический поиск активного клинического обсуждения по ключевым словам.
    Возвращает (тема, категория, рекомендуемый_тип) или None при затишье.
    """
    if len(chat_text) < 40:
        return None

    text_lower = chat_text.lower()

    # Проверка на батл материалов
    if any(m in text_lower for m in ["speedex", "спидекс", "а-силикон", "c-силикон", "бис-акрил", "батл материалов"]):
        return (
            "Батл материалов: С-силикон (Speedex) vs А-силикон или композитные материалы",
            "materials_battle",
            PollType.REGULAR
        )

    # Проверка клинических категорий
    for day_idx in (0, 1, 2, 3, 5, 6):
        rubric = WEEKLY_RUBRICATOR[day_idx]
        matches = [kw for kw in rubric["keywords"] if kw in text_lower]
        if len(matches) >= 2:
            return (
                f"Клинический разбор из чата: {rubric['topic'].split('(')[0].strip()}",
                rubric["category"],
                rubric["default_type"]
            )

    return None


async def _call_llm_adapter(caller: Callable, prompt: str, ctx: dict, timeout: float = 60.0):
    """Адаптер вызова LLM: пробует keyword 'status_ctx', затем позиционный аргумент, затем 'context'."""
    try:
        return await caller(prompt, status_ctx=ctx, timeout=timeout)
    except TypeError:
        try:
            return await caller(prompt, ctx, timeout=timeout)
        except TypeError:
            return await caller(prompt, context=ctx, timeout=timeout)


async def triage_topic_and_format(
    chat_context: Union[str, List[Any], None] = None,
    now: Optional[datetime.datetime] = None,
    llm_caller: Optional[Callable] = None,
    recent_polls: Optional[List[Dict[str, Any]]] = None
) -> TriageResult:
    """
    Шаг 1 и 2 многошагового пайплайна:
      1. Анализирует недавний контекст сообщений чата (за 24ч).
      2. Если есть бурное клиническое обсуждение — формирует тему по нему.
      3. Если затишье — выбирает тему из недельного клинического рубрикатора с учетом недавних тем.
      4. Определяет формат ('quiz', 'regular', 'lifestyle') и потребность в case_intro.
    """
    current_time = now or datetime.datetime.now()
    rubric = get_weekly_rubric(current_time, recent_polls=recent_polls)
    chat_text = extract_chat_text(chat_context)

    # Недавние темы для исключения дублирования
    antidup_topics_hint = ""
    if recent_polls:
        used_topics = [p.get("topic") for p in recent_polls if p.get("topic")]
        if used_topics:
            antidup_topics_hint = "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО выбирать недавно использованные темы:\n" + "\n".join(f"- {t}" for t in used_topics[:15])

    # Если передан LLM caller и есть достаточный контекст сообщений — используем AI-триаж
    if llm_caller is not None and len(chat_text) >= 50:
        triage_prompt = f"""
Ты — клинический триажер специализированного эндодонтического сообщества EndoChat.
Проанализируй последние сообщения врачей в чате:
\"\"\"
{chat_text[:2500]}
\"\"\"

День недели: {rubric['day_name']}. Тема рубрикатора на сегодня: {rubric['topic']}.

Определи:
1. Шло ли в чате активное клиническое обсуждение конкретного кейса, проблемы, осложнения или материала (например, Speedex vs А-силикон, непосадка коронки, перфорация)?
2. Если ДА — сформулируй узкую клиническую тему на базе обсуждения и выбери ТОЧНУЮ категорию специальности:
   - "endo" (эндодонтия, каналы, пульпит, периодонтит, МТА, апекс)
   - "ortho" (ортопедия, препарирование, коронки, виниры, уступы, оттиски, Ti-Base)
   - "surgery" (хирургия, имплантация, синус-лифтинг, удаление, торк)
   - "therapy" (терапия, кариес, реставрации, C-factor, бондинг, композиты)
   - "materials_battle" (батл материалов: слепочные массы, цементы, композиты)
   - "gnathology" (гнатология, ВНЧС, окклюзия, сплинт-терапия, сустав)
   - "council" (междисциплинарный клинический консилиум, неотложные состояния)
   Если НЕТ (затишье, общие фразы, флуд) — возьми тему из рубрикатора дня недели и категорию "{rubric['category']}".
3. Формат опроса:
   - "quiz": клиническая задача с 1 правильным ответом, объяснением в лампочке (💡).
   - "regular": опрос мнений / батл материалов / консенсус подходов (без правильного ответа, с процентами).
{antidup_topics_hint}
СТРОЖАЙШИЙ ЗАПРЕТ на любой бытовой юмор, несмешные аналогии (официанты, таксисты, быт) и кринж. Вопросы должны быть СТРОГО клиническими и доказательными (Evidence-Based Medicine).
4. Нужен ли отдельный вводный пост с клинической виньеткой/описанием случая (case_intro)? (true/false)

ЯЗЫК ОТВЕТА: СТРОГО РУССКИЙ. Все текстовые поля JSON — только на русском языке.
Выдай строго JSON:
{{
  "is_from_chat": true,
  "topic": "Краткая тема опроса",
  "category": "{rubric['category']}",
  "format_type": "quiz",
  "needs_case_intro": true,
  "rationale": "Краткое обоснование выбора"
}}
"""
        try:
            status_ctx = {"kind": "poll_triage", "thinking_level": "LOW", "temperature": 0.2}
            resp, err = await _call_llm_adapter(llm_caller, triage_prompt, status_ctx, timeout=30)
            text_resp = getattr(resp, "text", "") if resp else ""
            if not err and text_resp:
                cleaned = text_resp.strip()
                start = cleaned.find("{")
                end = cleaned.rfind("}")
                if start != -1 and end != -1:
                    data = json.loads(cleaned[start:end+1])
                    is_chat = bool(data.get("is_from_chat", False))
                    chosen_topic = str(data.get("topic", "")).strip()
                    fmt_str = str(data.get("format_type", "quiz")).lower()
                    if fmt_str == "regular":
                        p_type = PollType.REGULAR
                    elif fmt_str == "lifestyle":
                        p_type = PollType.LIFESTYLE
                    else:
                        p_type = PollType.QUIZ
                    needs_intro = bool(data.get("needs_case_intro", True))
                    rationale = str(data.get("rationale", ""))
                    valid_cats = set(CATEGORY_NAMES.keys())
                    raw_cat = str(data.get("category", "")).strip().lower()
                    cat = raw_cat if raw_cat in valid_cats else rubric["category"]

                    if chosen_topic:
                        return TriageResult(
                            topic=chosen_topic,
                            category=cat,
                            is_from_chat=is_chat,
                            format_type=p_type,
                            needs_case_intro=needs_intro,
                            rationale=rationale
                        )
        except Exception as e:
            logger.warning("LLM triage failed, falling back to heuristics: %s", e)

    # Эвристический триаж при отсутствии или сбое LLM
    heuristic = detect_chat_discussion_heuristic(chat_text)
    if heuristic:
        topic_name, cat, p_type = heuristic
        return TriageResult(
            topic=topic_name,
            category=cat,
            is_from_chat=True,
            format_type=p_type,
            needs_case_intro=(p_type == PollType.QUIZ),
            rationale="Обнаружено активное обсуждение клинических терминов в чате."
        )

    # Дефолт по рубрикатору (затишье в чате)
    return TriageResult(
        topic=rubric["topic"],
        category=rubric["category"],
        is_from_chat=False,
        format_type=rubric["default_type"],
        needs_case_intro=(rubric["default_type"] == PollType.QUIZ),
        rationale=f"Затишье в чате. Тема выбрана из рубрикатора дня недели ({rubric['day_name']})."
    )


