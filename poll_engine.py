def get_fallback_preset(
    category: Optional[str] = None,
    poll_type: Optional[PollType] = None,
    exclude_topics: Optional[List[str]] = None,
    recent_polls: Optional[List[Dict[str, Any]]] = None
) -> PollPayload:
    """
    Выбирает проверенный клинический пресет из пула фолбэков (42 пресета).
    Исключает дублирование с недавними опросами (recent_polls за 30-45 дней)
    и темами из exclude_topics.
    """
    candidates = list(POLL_FALLBACK_PRESETS)

    if category:
        filtered = [p for p in candidates if p.get("category") == category]
        if filtered:
            candidates = filtered

    if poll_type:
        filtered_by_type = [p for p in candidates if p.get("poll_type") == poll_type]
        if filtered_by_type:
            candidates = filtered_by_type

    if exclude_topics:
        excluded_set = {str(t).strip().lower() for t in exclude_topics if t}
        non_excluded = [p for p in candidates if str(p.get("topic", "")).strip().lower() not in excluded_set]
        if non_excluded:
            candidates = non_excluded

    if recent_polls:
        try:
            import poll_storage
            fresh_candidates = []
            for p in candidates:
                is_dup, _ = poll_storage.is_duplicate_poll(
                    question=p.get("question", ""),
                    topic=p.get("topic", ""),
                    recent_polls=recent_polls,
                    threshold=0.55
                )
                if not is_dup:
                    fresh_candidates.append(p)
            if fresh_candidates:
                candidates = fresh_candidates
        except Exception as dup_err:
            logger.warning("Error filtering fallback presets against recent_polls: %s", dup_err)

    chosen = dict(random.choice(candidates))
    chosen["source"] = "fallback"
    payload = sanitize_poll_payload(chosen)
    if payload is None:
        # Абсолютный сейфти-нет
        return PollPayload(
            question="Поиск скрытого устья MB2 канала в моляре 1.6 под микроскопом. Оптимальный ориентир?",
            options=[
                "По линии перешейка от MB1 медиально-небно на 1-2 мм",
                "По центру мезиального краевого гребня",
                "На уровне устья дистально-щечного канала",
                "В зоне фуркации на дне пульпарной камеры"
            ],
            poll_type=PollType.QUIZ,
            correct_option_id=0,
            explanation_brief="MB2 располагается на линии перешейка от MB1 в небном направлении на 1-2 мм.",
            explanation_deep="По анатомическим исследованиям Krasner & Rankow устье MB2 локализуется на перешейке медиально-небно от MB1 в более чем 90% первых верхних моляров.",
            topic="Эндодонтия: поиск MB2 канала",
            source="fallback"
        )
    return payload


