# ШАГ 3.5: КЛИНИЧЕСКИЙ РЕЦЕНЗЕНТ (QUALITY GATE)
# ==============================================================================

async def review_poll_quality(
    payload: PollPayload,
    llm_caller: Callable,
    timeout: float = 85.0
) -> Tuple[bool, List[str]]:
    """
    Шаг 3.5 пайплайна — клинический контроль качества (11 критериев).

    Выполняет независимый LLM-вызов для проверки сгенерированного опроса
    на галлюцинации, межсекционные ошибки, перегруз соматикой и структурные дефекты.

    Returns:
        (True, [])           — опрос прошёл, можно публиковать.
        (False, [дефекты])   — отклонён, список дефектов для retry-промпта.
    """
    options_text = "\n".join(
        f"  [{i}] {opt}" for i, opt in enumerate(payload.options)
    )
    correct_idx = payload.correct_option_id
    correct_label = (
        f"[{correct_idx}] {payload.options[correct_idx]}"
        if correct_idx is not None and 0 <= correct_idx < len(payload.options)
        else "нет (опрос мнений)"
    )
    category = payload.category or "неизвестно"
    cat_display = CATEGORY_NAMES.get(category, category)
    poll_type = payload.poll_type.value if payload.poll_type else "quiz"

    review_prompt = f"""Ты — главный врач-редактор клинического телеграм-канала для практикующих стоматологов.
Тебе на проверку поступил автоматически сгенерированный опрос. Оцени его по 12 универсальным критериям.

КАТЕГОРИЯ ОПРОСА: {cat_display} (код: {category})
ТИП: {poll_type}
КЛИНИЧЕСКИЙ КЕЙС (case_intro): {payload.case_intro or "(нет)"}
ВОПРОС: {payload.question}
ВАРИАНТЫ:
{options_text}
ПРАВИЛЬНЫЙ ОТВЕТ: {correct_label}
КРАТКОЕ ОБЪЯСНЕНИЕ: {payload.explanation_brief or "(нет)"}
РАЗБОР: {payload.explanation_deep or "(нет)"}

КРИТЕРИИ ОТКЛОНЕНИЯ (хотя бы один нарушен = REJECT):

1. ДИСЦИПЛИНАРНАЯ СОГЛАСОВАННОСТЬ
   Каждый термин, тест, материал, процедура в вопросе и вариантах должны реально
   использоваться именно в указанной дисциплине (категория: {cat_display}).
   Запрещено смешивать несвязанные дисциплины (напр. эндодонтический силер при фиксации коронок, проба Вальсальвы при кариесе) → REJECT.

2. СУЩЕСТВОВАНИЕ ПРОТОКОЛОВ И ПРОЦЕДУР
   Каждая диагностическая или лечебная процедура должна реально существовать
   и применяться в современной клинической практике у кресла. Выдуманная или невозможная процедура → REJECT.

3. ЛОГИЧЕСКАЯ ОДНОРОДНОСТЬ ВАРИАНТОВ
   Все варианты должны решать одну и ту же клиническую задачу на одном и том же
   этапе принятия решений. Варианты из разных этапов лечения, разных
   специальностей или не являющиеся реальными альтернативами друг другу → REJECT.

4. ОТСУТСТВИЕ ВАРИАНТНОЙ ТАВТОЛОГИИ
   Два и более вариантов не должны быть семантически идентичны (одно и то же,
   перефразированное разными словами). Такой опрос не имеет смысла → REJECT.

5. НАЛИЧИЕ РЕАЛЬНОЙ КЛИНИЧЕСКОЙ ДИЛЕММЫ (для типа quiz)
   Правильный ответ не должен быть единственным очевидным и тривиальным вариантом,
   который любой стажёр выберет без раздумий. Дилемма должна быть настоящей:
   опытные врачи реально расходятся во мнениях → иначе REJECT.

6. СВЯЗНОСТЬ КЕЙСА И ВОПРОСА
   Если есть case_intro, вопрос должен прямо вытекать из описанной клинической ситуации.
   Вопрос, никак не связанный с описанным кейсом или противоречащий ему → REJECT.

7. ЛАКОНИЧНОСТЬ КЕЙСА И ВОПРОСА
   Вопрос — максимум два предложения (до 300 символов).
   Клинический кейс (case_intro, если есть) — краткая виньетка строго в 1-3 предложения (до 400 символов!).
   Если case_intro представляет собой простыню на 3+ абзаца или занудный протокол с длинным анамнезом жизни → REJECT.

8. КЛИНИЧЕСКАЯ КОРРЕКТНОСТЬ И ГЛУБИНА РАЗБОРА (только для типа quiz)
   Вариант, отмеченный как правильный, должен соответствовать действующим
   доказательным протоколам. Явное противоречие EBM или клинически опасная тактика → REJECT.
   Поле explanation_deep должно соответствовать протоколу анализа опроса (POLL DEBRIEF CORE):
   вскрывать анатомию типичного заблуждения, показывать последствия второго порядка и доказывать победу первого принципа, а не быть пустой отпиской → иначе REJECT.

9. БЕЗОПАСНОСТЬ ДИСТРАКТОРОВ
   Неправильные варианты не должны представлять реально опасную или ятрогенную
   тактику как нейтральную клиническую альтернативу без какого-либо маркера.
   «Ничего не делать» при острой патологии или грубая ятрогения как
   нормальный вариант выбора → REJECT.

10. РЕЛЕВАНТНОСТЬ АУДИТОРИИ
    Вопрос должен быть практической дилеммой у кресла для оперирующего врача-стоматолога.
    Академическое заучивание (определения, составы, классификации без кейса),
    бытовые аналогии, лайфстайл-вопросы в типе quiz → REJECT.

11. НЕТ ИСКУССТВЕННЫХ СОПУТСТВУЮЩИХ ПАТОЛОГИЙ («ИНВАЛИДОВ»)
    Если в кейс необоснованно напиханы соматические патологии (сахарный диабет, приём антикоагулянтов, бруксизм, курение), которые никак не определяют суть стоматологического выбора на данном этапе — REJECT. Пациент должен быть обычным сохранным амбулаторным пациентом, если тема не посвящена неотложным состояниям или хирургии на фоне соматики.

12. ЗАПРЕТ НА МАТЕРИАЛОВЕДЧЕСКУЮ ЗУБРЕЖКУ И МИЛЛИМЕТРОВЫЙ ФАНАТИЗМ (CRITICAL)
    Если вопрос или варианты тестируют:
    - металлургические марки стали и сплавов файлов (M-Wire, CM-Wire, мартенсит/аустенит, титан Grade 4 vs Grade 5);
    - поколения и кристаллографические фазы циркония (3Y-TZP, 4Y, 5Y, кубическая фаза, % иттрия, точные МПа прочности 1200 vs 600);
    - заучивание долей миллиметров и углов (уступ 0.3 мм vs 0.5 мм, угол 4° vs 6°);
    - абстрактные формулы и физико-химические константы (ГПа, КТР, % усадки)
    ВМЕСТО реальной клинической тактики у кресла и понятных практических показаний (E.max vs Циркон во фронте/боковом отделе, штифт vs монолит, сохранение зуба vs удаление, тактика при осложнениях) → REJECT.

13. ЗАПРЕТ НА ДУШНУЮ АКАДЕМИЧЕСКУЮ ЗАУМЬ И АББРЕВИАТУРЫ КОМИТЕТОВ (CRITICAL)
    Если в вопросе, вариантах, explanation_brief или explanation_deep используются бюрократические штампы:
    «По консенсусу ESE и AAE», «согласно рекомендациям европейского/американского общества», «по гайдлайнам ITI/EFP/Cochrane» вместо чистой клинической логики у кресла → REJECT. Обоснование должно строиться на биологических и биомеханических фактах (сохранение дентина, отсутствие герметизма, концентрация напряжений, химический ожог периодонта), а не на зарубежных аббревиатурах!

14. КАЧЕСТВО И ПРАВДОПОДОБИЕ ДИСТРАКТОРОВ (ЗАПРЕТ НА КАРИКАТУРНЫЕ/ГЛУПЫЕ ВАРИАНТЫ)
    Каждый неверный вариант ответа ДОЛЖЕН быть правдоподобной, клинически грамотной альтернативой (спорный протокол другой школы, популярная клиническая ошибка, компромиссное решение).
    КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНЫ:
    - Карикатурно-абсурдные варианты (например: 'высверливание бором до верхушки', 'спилить 1 мм коронки', 'боксерская капа у кресла', 'отказ от имплантации навсегда', 'пломбирование фосфат-цементом', 'удалить зуб при рядовой проблеме').
    - Заведомо бредовые или шуточные варианты, превращающие викторину в тест с 1 очевидным ответом и 3 глупыми заглушками.
    Если среди вариантов есть хотя бы один карикатурный/глупый дистрактор → REJECT.

ЕСЛИ ДЕФЕКТОВ НЕТ — верни PASS. Не придирайся к стилю, опечаткам, выбору FDI-номера зуба.
Если REJECT — опиши дефекты кратко и конкретно, чтобы автор мог исправить каждый.

ЯЗЫК ДЕФЕКТОВ: СТРОГО РУССКИЙ. Поле "defects" — только на русском языке.
Ответь СТРОГО валидным JSON (без markdown, без пояснений):
Если дефектов нет:
{{"verdict": "PASS", "defects": []}}

Если есть нарушения:
{{"verdict": "REJECT", "defects": ["описание дефекта 1", "описание дефекта 2"]}}
"""

    status_ctx = {"kind": "poll_clinical_review", "thinking_level": "HIGH", "temperature": 0.2}
    try:
        resp, err = await _call_llm_adapter(llm_caller, review_prompt, status_ctx, timeout=timeout)
    except Exception as exc:
        logger.warning("Clinical reviewer call raised exception: %s", exc)
        return False, [f"Исключение при вызове рецензента: {exc}"]

    if err or not resp or not getattr(resp, "text", None):
        logger.warning("Clinical reviewer LLM unavailable (err=%s)", err)
        return False, [f"Рецензент недоступен: {err}"]

    raw = resp.text.strip()
    start = raw.find("{")
    end = raw.rfind("}")
    if start == -1 or end == -1:
        logger.warning("Clinical reviewer returned non-JSON output: %s", raw[:200])
        return False, ["Рецензент вернул невалидный JSON"]

    result = None
    try:
        result = json.loads(raw[start:end + 1], strict=False)
    except Exception as parse_exc:
        verdict_m = re.search(r'"verdict"\s*:\s*"([^"]+)"', raw, re.IGNORECASE)
        if verdict_m:
            verdict_val = verdict_m.group(1).strip().upper()
            defects_list = []
            defects_m = re.search(r'"defects"\s*:\s*\[(.*?)\]', raw, re.DOTALL)
            if defects_m:
                defects_raw = defects_m.group(1)
                defects_list = [
                    d.strip().strip('"').strip("'")
                    for d in re.split(r'",\s*"|\',\s*\'', defects_raw)
                    if d.strip()
                ]
            result = {"verdict": verdict_val, "defects": defects_list}
        else:
            logger.warning("Clinical reviewer JSON parse error: %s", parse_exc)
            return False, [f"Ошибка парсинга ответа рецензента: {parse_exc}"]

    verdict = str(result.get("verdict", "")).strip().upper()
    defects: List[str] = result.get("defects", [])

    if verdict != "PASS":
        logger.warning(
            "Clinical reviewer REJECTED poll (category=%s, type=%s). Defects: %s",
            category, poll_type, defects
        )
        return False, defects or ["Опрос не прошёл клинический контроль качества"]

    logger.info("Clinical reviewer PASSED poll (category=%s, verdict=%s)", category, verdict)
    return True, []



