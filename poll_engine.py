# ОСНОВНОЙ ДВИЖОК POLL ENGINE (МНОГОШАГОВЫЙ ПАЙПЛАЙН)
# ==============================================================================

class PollEngine:
    """
    Многошаговый AI-движок генерации опросов и викторин для StomChat.
    """

    def __init__(self, default_llm_caller: Optional[Callable] = None):
        self.default_llm_caller = default_llm_caller

    async def _resolve_llm_caller(self, caller: Optional[Callable] = None) -> Optional[Callable]:
        if caller is not None:
            return caller
        if self.default_llm_caller is not None:
            return self.default_llm_caller
        try:
            import blocking_tools
            return blocking_tools.generate_gemini_text_async
        except ImportError:
            return None

    async def run_pipeline(
        self,
        chat_context: Union[str, List[Any], None] = None,
        now: Optional[datetime.datetime] = None,
        force_topic: Optional[str] = None,
        force_type: Optional[PollType] = None,
        llm_caller: Optional[Callable] = None,
        is_anonymous: bool = True,
        open_period: Optional[int] = None
    ) -> Tuple[PollPayload, types.InputMediaPoll]:
        """
        Запуск полного 5-шагового пайплайна:
          Шаг 1: Контекстный триаж темы (чат vs рубрикатор).
          Шаг 2: Триаж формата ('quiz', 'regular', 'lifestyle').
          Шаг 3: Генерация контента через LLM.
          Шаг 4: Санитизация и проверка лимитов.
          Шаг 5: Переход на проверенные фолбэки при сбое.
          Telethon Builder: Сборка InputMediaPoll.
        """
        current_time = now or datetime.datetime.now()
        active_llm = await self._resolve_llm_caller(llm_caller)

        # Шаг 1 и 2: Триаж
        triage = await triage_topic_and_format(
            chat_context=chat_context,
            now=current_time,
            llm_caller=active_llm
        )

        if force_topic:
            triage.topic = force_topic
        if force_type:
            triage.format_type = force_type
            if force_type != PollType.QUIZ:
                triage.needs_case_intro = False

        logger.info(
            "Poll triage complete: topic='%s', type=%s, from_chat=%s",
            triage.topic, triage.format_type.value, triage.is_from_chat
        )

        payload: Optional[PollPayload] = None

        # Шаг 3–3.5: Генерация + клинический рецензент, до 3 попыток (оригинал + 2 retry)
        MAX_GENERATION_ATTEMPTS = 3
        last_critique: Optional[List[str]] = None

        if active_llm is not None:
            for attempt in range(1, MAX_GENERATION_ATTEMPTS + 1):
                try:
                    candidate = await generate_poll_content(
                        triage=triage,
                        llm_caller=active_llm,
                        critique=last_critique,
                    )
                except Exception as gen_err:
                    logger.warning("Generation error (attempt %d): %s", attempt, gen_err)
                    candidate = None

                if candidate is None:
                    logger.warning("Generation returned None on attempt %d — retrying next attempt...", attempt)
                    last_critique = ["Предыдущая генерация завершилась ошибкой или вернула невалидный JSON. Сгенерируй строго валидный JSON по схеме."]
                    continue

                # Клинический рецензент
                try:
                    passed, defects = await review_poll_quality(
                        payload=candidate, llm_caller=active_llm
                    )
                except Exception as review_err:
                    logger.warning("Reviewer raised exception (attempt %d): %s — failing safe", attempt, review_err)
                    passed, defects = False, [f"Исключение рецензента: {review_err}"]

                if passed:
                    logger.info(
                        "Poll passed clinical review on attempt %d (category=%s, topic='%s')",
                        attempt, triage.category, triage.topic
                    )
                    payload = candidate
                    break

                logger.warning(
                    "Poll REJECTED on attempt %d/%d (category=%s). Defects: %s",
                    attempt, MAX_GENERATION_ATTEMPTS, triage.category, defects
                )
                last_critique = defects or ["Содержит клинические ошибки или галлюцинации — сгенерируй заново с нуля"]

                if attempt == MAX_GENERATION_ATTEMPTS:
                    logger.error(
                        "All %d generation attempts rejected — falling back to preset (category=%s)",
                        MAX_GENERATION_ATTEMPTS, triage.category
                    )

        # Шаг 5: Фолбэк при недоступности или ошибке LLM / отклонении рецензентом
        if payload is None:
            logger.info("Using reliable fallback preset for category=%s", triage.category)
            payload = get_fallback_preset(category=triage.category, poll_type=triage.format_type)

        # Сборка Telethon MTProto объекта
        media = build_poll_media(
            question=payload.question,
            options=payload.options,
            poll_type=payload.poll_type.value,
            correct_idx=payload.correct_option_id,
            explanation=payload.explanation_brief,
            is_anonymous=is_anonymous,
            open_period=open_period
        )

        return payload, media


